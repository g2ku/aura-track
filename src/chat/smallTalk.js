// Не вопрос о цифрах, а разговор: «привет», «спасибо», «что ты умеешь».
//
// Раньше на всё это ассистент отвечал «Не распознал вопрос», а «что ты
// умеешь» искал как товар «ты умеешь» (прогон 28.09.2026). Здесь — только
// реплики целиком: «привет, касса вчера» — это вопрос, его разберут правила.
//
// Возвращает { kind, text } или null.

const HELP = [
  "Считаю по Poster — по сети, точке или ИП:",
  "• Касса и чеки: «касса вчера», «чеки на Абае за неделю», «средний чек за месяц»",
  "• Сравнения: «сравни Абая и Дубай», «кто просел за неделю», «сравни сентябрь и август по чекам», «доля Атакента в кассе»",
  "• Товары и цены: «топ 10 товаров за неделю», «сколько капучино 450 продали», «самый дорогой напиток»",
  "• Время и дни: «во сколько пик», «касса по неделям за сентябрь», «лучший день недели»",
  "• Прогноз и причины: «прогноз на конец месяца», «почему просела касса вчера»",
  "• Люди: «кто работал вчера», «кто лучше всех продаёт за неделю»",
  "",
  "Короткие уточнения понимаю: после ответа можно спросить «а вчера?», «а на Гагарина?», «а чеки?».",
].join("\n");

const clean = (q) => String(q || "").toLowerCase().replace(/ё/g, "е").replace(/[!?.,)(:;]+/g, " ").replace(/\s+/g, " ").trim();

export function smallTalk(q) {
  const t = clean(q);
  if (!t) return null;
  if (/^(?:помощь|помоги|help|справка|подсказка|что (?:ты )?(?:умеешь|можешь)|что умеешь|что можешь|как (?:тобой )?пользоваться|какие (?:есть )?вопросы|что (?:можно )?(?:у тебя )?спросить|что ты знаешь|кто ты|ты кто)$/.test(t)) {
    return { kind: "help", text: HELP };
  }
  if (/^(?:привет|приветик|здравствуй(?:те)?|здрасте|салам|салем|сәлем|добрый (?:день|вечер)|доброе утро|доброй ночи|хай|hi|hello)(?: (?:всем|бот|ассистент))?$/.test(t)) {
    return { kind: "hello", text: `Привет! Спросите про кассу, чеки, товары или точки — например, «касса вчера» или «кто просел за неделю».` };
  }
  if (/^(?:спасибо|спс|благодарю|рахмет|thanks|thank you|спасибо большое|большое спасибо|пасиб[оа]?)(?: (?:большое|огромное|бот))?$/.test(t)) {
    return { kind: "thanks", text: "Пожалуйста! Спрашивайте, если что-то ещё посчитать." };
  }
  if (/^(?:пока|до свидания|до встречи|бай)$/.test(t)) {
    return { kind: "bye", text: "До встречи!" };
  }
  return null;
}
