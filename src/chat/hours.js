// Часы, когда сеть работает, — для «тихих часов». Одно на сайт и бота.
//
// Ночью открыта одна Гагарина (до 03:00), и тихими часами всей сети
// выходили 00:00–03:00 с её 3 200 ₸ за час (живая проверка 27.09.2026) —
// правда, но не про то: тихий час — это когда точки открыты, а людей нет.
// Считаем рабочими часы, в которые продавало большинство точек (больше
// половины: из восьми — пять, из двух — обе).
//
// spotsAt — по часам множество пар «день|точка» с продажами; total —
// сколько таких пар вообще. За месяц у восьми точек найдётся по чеку и в
// полночь — поэтому считаем дни: час рабочий, если в нём продавало
// большинство точко-дней. Одна точка за один день — все её часы рабочие.
export function workingHour(spotsAt, total) {
  const need = Math.floor((total || 0) / 2) + 1;
  return (h) => (spotsAt?.[h]?.size || 0) >= need;
}
